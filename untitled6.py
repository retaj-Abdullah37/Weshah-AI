def generate_intro_expl(row, max_new_tokens=260, retries=6):
    model.eval()

    poet  = normalize_ar(row.get(POET_COL))
    title = normalize_ar(row.get(TITLE_COL))
    cls   = normalize_ar(row.get(CLS_COL))
    text_full = clean(row.get(TEXT_COL))
    wb = words_block(row)

    text_for_prompt = text_full[:1200]

    system_msg = (
        "أنت كاتب أدبي عربي متخصص في الموشحات الأندلسية. "
        "اكتب بالعربية الفصحى السليمة فقط. "
        "ممنوع أي لغة أجنبية أو أحرف غير عربية. "
        "ممنوع تكرار العناوين أو تكرار الفقرات. "
        "لا تخترع أسماء أو معلومات غير موجودة. "
        "اكتب فقط قسمين: تمهيد ثقافي ثم شرح مبسط."
    )

    user_msg = f"""اكتب فقط النص التالي وبنفس الصيغة حرفيًا (سطرين عناوين + فقرتين):

✨ التمهيد الثقافي:
(فقرة واحدة 3-5 جمل)

💡 الشرح المبسط:
(فقرة واحدة 5-7 جمل)

شروط صارمة:
- لا تكرر أي عنوان أو فقرة.
- لا تكتب "التمهيد الثقافي:" داخل الفقرة.
- لا تكتب "الشرح المبسط:" داخل الفقرة.
- لا تذكر الشاعر/العنوان/التصنيف داخل الفقرتين.
- لا تقتبس أبياتًا.
- توقف بعد الشرح مباشرة.

للاطلاع فقط:
نص الموشح:
{text_for_prompt}

الكلمات الصعبة ومعانيها:
{wb}
"""

    messages = [
        {"role":"system","content":system_msg},
        {"role":"user","content":user_msg},
    ]

    prompt = tok.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    inputs = tok(prompt, return_tensors="pt").to(model.device)

    last_final = ""
    for _ in range(retries):
        with torch.no_grad():
            out_ids = model.generate(
                **inputs,
                max_new_tokens=max_new_tokens,
                do_sample=False,
                repetition_penalty=1.22,
                eos_token_id=tok.eos_token_id,
                pad_token_id=tok.eos_token_id
            )

        new_tokens = out_ids[0][inputs["input_ids"].shape[-1]:]
        gen = tok.decode(new_tokens, skip_special_tokens=True)

        intro, expl = extract_first_intro_expl(gen)
        final = format_final(intro, expl, poet, title, cls)
        last_final = final

        if looks_ok(final):
            return final

    return last_final if last_final else "❌ ما طلع نص."


# ---- Arabic cleanup ----
ARABIC_ONLY = re.compile(
    r"[^\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF0-9\s\.\,\!\?\:\;\-\–\—\(\)\[\]\{\}«»\"\'\nـ]"
)
AR_LET = re.compile(r"[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF]")

def fix_arabic_spacing(text: str) -> str:
    if not text: return ""
    text = re.sub(r"[\u200f\u200e\u202a-\u202e\u2066-\u2069]", " ", text)
    text = re.sub(r"[ \t]+", " ", text).strip()
    text = re.sub(r"\bال\s+([اأإآء-ي])", r"ال\1", text)
    text = re.sub(r"\b([وفبكلس])\s+([اأإآء-ي])", r"\1\2", text)
    text = re.sub(r"\bالم\s+([اأإآء-ي])", r"الم\1", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text

COMMON_FIXES = [
    (r"\bتمهد\b", "تمهيد"),
    (r"\bثقالي\b", "ثقافي"),
    (r"\bالم بسط\b", "المبسط"),
    (r"\bالمتو ع(?:ة|ه)\b", "المتنوعة"),
    (r"\bتتمة الثقافة\b", ""),
    (r"\bالشرح\s*:\b", ""),
]

def clean_arabic_output(text: str) -> str:
    text = (text or "").strip()
    text = ARABIC_ONLY.sub("", text)
    text = fix_arabic_spacing(text)
    for pat, rep in COMMON_FIXES:
        text = re.sub(pat, rep, text)
    text = re.sub(r"\n{3,}", "\n\n", text).strip()
    text = re.sub(r"\s+", " ", text).strip()
    return text

# ---- Robust header extraction (works even if no ✨💡 and even if in one line) ----
INTRO_TAG = "✨ التمهيد الثقافي:"
EXPL_TAG  = "💡 الشرح المبسط:"

def standardize_tags(t: str) -> str:
    t = (t or "").strip()

    # unify different header spellings into standard tags
    t = re.sub(r"(✨\s*)?التمهيد\s*الثقافي\s*[:：\-]?", INTRO_TAG, t)
    t = re.sub(r"(💡\s*)?الشرح\s*المبسط\s*[:：\-]?", EXPL_TAG, t)

    # also handle "تمهيد ثقافي" without "ال"
    t = re.sub(r"(✨\s*)?تمهيد\s*ثقافي\s*[:：\-]?", INTRO_TAG, t)
    t = re.sub(r"(💡\s*)?شرح\s*مبسط\s*[:：\-]?", EXPL_TAG, t)

    return t

def extract_first_intro_expl(raw: str):
    t = clean_arabic_output(raw)
    t = standardize_tags(t)

    # ensure tags exist
    if INTRO_TAG not in t or EXPL_TAG not in t:
        # fallback: split into 2 chunks
        parts = re.split(r"\.|\!|\؟|\?", t)
        parts = [p.strip() for p in parts if p.strip()]
        intro = " ".join(parts[:2]).strip()
        expl  = " ".join(parts[2:6]).strip()
        return intro, expl

    # take from first intro to first expl after it
    t = t[t.find(INTRO_TAG):].strip()
    before, after = t.split(EXPL_TAG, 1)
    intro = before.replace(INTRO_TAG, "").strip()

    # cut explanation at any repeated tag
    stop_positions = []
    for m in [INTRO_TAG, EXPL_TAG]:
        j = after.find(m)
        if j != -1:
            stop_positions.append(j)
    expl = after[:min(stop_positions)] if stop_positions else after
    expl = expl.strip()

    return intro, expl

def strip_inner_labels(s: str) -> str:
    # remove repeated labels inside content
    s = re.sub(r"(✨\s*)?التمهيد\s*الثقافي\s*[:：\-]?", "", s)
    s = re.sub(r"(💡\s*)?الشرح\s*المبسط\s*[:：\-]?", "", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s

def scrub_forbidden(s: str, poet: str, title: str, cls: str) -> str:
    # remove accidental mentions of poet/title/class inside generated text
    for v in [poet, title, cls]:
        v = (v or "").strip()
        if v:
            s = s.replace(v, "")
    s = re.sub(r"\s+", " ", s).strip()
    return s

def format_final(intro: str, expl: str, poet: str, title: str, cls: str) -> str:
    intro = clean_arabic_output(intro)
    expl  = clean_arabic_output(expl)

    intro = strip_inner_labels(intro)
    expl  = strip_inner_labels(expl)

    intro = scrub_forbidden(intro, poet, title, cls)
    expl  = scrub_forbidden(expl, poet, title, cls)

    return f"{INTRO_TAG}\n{intro}\n\n{EXPL_TAG}\n{expl}".strip()

def looks_ok(final_text: str) -> bool:
    if not final_text: return False
    if INTRO_TAG not in final_text or EXPL_TAG not in final_text: return False
    if not AR_LET.search(final_text): return False
    if len(final_text) < 120: return False
    if re.search(r"[A-Za-z\u4e00-\u9fff]", final_text): return False
    return True

